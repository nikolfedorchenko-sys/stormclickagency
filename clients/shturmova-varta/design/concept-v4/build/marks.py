# Три знаки концепції v4. Поле 120×120 (у SVG-одиницях), y донизу.
import math
from prims import *

R2 = math.sqrt(2)


# ---------- A «Лігатура»: Ш і В зі спільною стійкою і спільною основою ----------
# Модуль u = 5, поле 24u. Стійка 3u, просвіт 3u, горизонталі 14 (оптично тонші за стійку 15).
def mark_a(variant='main'):
    u = 5; s = 15; g = 15; hb = 14
    W3 = 3 * s + 2 * g                        # ширина «Ш» = 75
    H = 120; mid0, mid1 = 52, 52 + hb         # середня перекладина «В» – трохи вище центру
    # силует
    sil = U(rect(0, 0, W3, H),
            bowl(W3 - 1, 0, mid1, flat=8),     # верхня чаша (менша)
            bowl(W3 - 1, mid0, H, flat=10))    # нижня чаша (більша)
    # просвіти «Ш»: U-подібні, з круглим дном (радіус = півпросвіту)
    cnt = []
    for i in range(2):
        x = s + i * (s + g)
        cnt.append(rect(x, -1, g, H - hb + 1))
    # просвіти «В»: та сама логіка, що й зовнішній контур, але з товщиною дуги 15.5
    up_in = bowl(W3, hb, mid0, flat=6.5)
    lo_in = bowl(W3, mid1, H - hb, flat=8.5)
    m = D(sil, *cnt, up_in, lo_in)
    return m


# ---------- B «Курс»: два шеврони вперед, гострий кут 60°, зрізи паралельні руху ----------
def chevron(tip_x, cy, half_h, t, ang=60):
    """Шеврон вістрям праворуч. ang – кут при вершині. t – товщина по нормалі.
    Кінці плечей зрізано горизонтально (уздовж напрямку руху)."""
    a = math.radians(ang / 2)
    depth = half_h / math.tan(a)              # на скільки плечі відходять назад
    th = t / math.sin(a)                      # товщина по горизонталі
    tv = t / math.cos(a)                      # товщина по вертикалі (для зрізу)
    x0 = tip_x - depth
    # зовнішній контур: верхній кінець (x0, cy-half_h) → вістря → нижній кінець
    pts = [(x0, cy - half_h), (x0 + th, cy - half_h), (tip_x, cy), (x0 + th, cy + half_h), (x0, cy + half_h),
           (tip_x - th, cy)]
    return poly(pts), th


def mark_b(variant='main', tips=(98, 61), gap=10.5):
    """Квадрат (об'єкт під охороною), розсічений двома шевронними просвітами під 45°.
    Виходить три частини: вістря, шеврон і хвостовик – рух уперед, два рубежі."""
    S = 120; gh = gap * R2; cuts = []
    for tx in tips:
        cuts.append(poly([(tx - 60, -1), (tx - 60 + gh, -1), (tx + gh, 60), (tx - 60 + gh, 121), (tx - 60, 121), (tx, 60)]))
    return D(rect(0, 0, S, S), *cuts)


# ---------- C «Вартовий»: сова анфас, суворі брови-шеврон, очі – негативний простір ----------
def owl_layers():
    """Сова: голова (з просвітами очей і дзьоба), білки очей, зіниці. Поле 120, модуль 5."""
    W = 120; H = 120; notch = 24; ch = 30
    # силует: квадрат з V-вирізом угорі (пір'яні «вушка») і фасками 45° внизу (6 модулів)
    head = poly([(0, 0), (60, notch), (120, 0), (120, H - ch), (120 - ch, H), (ch, H), (0, H - ch)])
    # очі: кола r=21, верх зрізано лінією брови з нахилом 0.24 – погляд пильний, але не злий
    ex, ey, er = 33, 70, 21
    brow_y = lambda x: 59 - abs(x - 60) * 0.24
    eyes = U(circle(ex, ey, er), circle(W - ex, ey, er))
    brow = poly([(-10, -30), (-10, brow_y(-10)), (60, brow_y(60)), (130, brow_y(130)), (130, -30)])
    eyes = D(eyes, brow)
    # зіниці зміщені до центру й донизу – погляд зібраний на того, хто дивиться
    pupils = U(circle(ex + 4, ey + 4, 8), circle(W - ex - 4, ey + 4, 8))
    # дзьоб: трикутник вістрям донизу (не ромб і не «ніс» черепа)
    beak = poly([(53.5, 91), (66.5, 91), (60, 107)])
    return dict(head=D(head, eyes, beak), eyes=D(eyes, pupils), pupils=pupils, beak=beak, whites=eyes)


def mark_c(variant='main'):
    L = owl_layers()
    return U(L['head'], L['pupils'])


