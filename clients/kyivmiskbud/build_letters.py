def build(letter, out_dir):
    doc = Document(); base_styles(doc)
    setup_section(doc.sections[0])

    para(doc, "На № 107-2530 від 19.03.2026", align=WD_ALIGN_PARAGRAPH.LEFT, before=170)  # місце під бланк, дату і номер – канцелярія
    for i, line in enumerate(["Голові Святошинської районної",
                              "в місті Києві державної адміністрації",
                              "Георгію ЗАНТАРАЇ"]):
        para(doc, line, left=90, align=WD_ALIGN_PARAGRAPH.LEFT, before=18 if i == 0 else 0)

    t = para(doc, letter["title"], bold=True, align=WD_ALIGN_PARAGRAPH.LEFT, before=24)
    t.paragraph_format.right_indent = Mm(97)  # ширина заголовка 73 мм
    para(doc, "Шановний пане Георгію!", align=WD_ALIGN_PARAGRAPH.CENTER, before=18, after=12)

    order_full = (f"Додатка 1 до наказу Департаменту комунальної власності м. Києва "
                  f"від 30.09.2025 {letter['order']}")
    body = [
        f"На виконання Вашого листа від 19.03.2026 № 107-2530 ПрАТ «Холдингова компанія «Київміськбуд» (далі – Товариство) направляє пакет документів для безоплатної передачі до комунальної власності територіальної громади міста Києва {letter['object']}, підготовлений відповідно до {order_full}.",
        f"Рішення про безоплатну передачу прийнято правлінням і наглядовою радою Товариства ({DECISIONS}).",
        f"Просимо розглянути подані документи та ініціювати підготовку розпорядчого документа про безоплатне прийняття до комунальної власності територіальної громади міста Києва {letter['object']}.",
    ]
    if letter.get("extra"):
        body.insert(2, letter["extra"])
    for t in body:
        para(doc, t, indent_first=10, spacing=1.15)

    para(doc, "Додатки:", align=WD_ALIGN_PARAGRAPH.LEFT, before=18, keep=True)
    for i, d in enumerate(letter["docs"], 1):
        p = para(doc, f"{i}. {d} на [__] арк. в 1 прим.", align=WD_ALIGN_PARAGRAPH.LEFT)
        p.paragraph_format.left_indent = Mm(6); p.paragraph_format.first_line_indent = Mm(-6)

    p = para(doc, "", align=WD_ALIGN_PARAGRAPH.LEFT, before=36)
    p.paragraph_format.tab_stops.add_tab_stop(Mm(170), WD_TAB_ALIGNMENT.RIGHT)
    add_runs(p, "Голова правління\tВалерій ЗАСУЦЬКИЙ")

    path = f"{out_dir}/{letter['file']}.docx"
    doc.save(path)
    return path


if __name__ == "__main__":
    for l in LETTERS:
        print(build(l, sys.argv[1]))
